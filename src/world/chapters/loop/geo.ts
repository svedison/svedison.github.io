// The Loop: geography of the Pacific rim as data.
// Coastlines are hand-simplified from real coordinates (lat °N, lon °E with the Americas as 360 - °W), so the map
// reads as the real Pacific at a glance without shipping any map data. Projection is Mercator, Pacific-centred.

export type LatLon = [lat: number, lon: number];

/** World units per radian of Mercator. */
export const MAP_SCALE = 40;
export const CENTER_LON = 178;
const CENTER_MERC = merc(40);

function merc(lat: number): number {
  const p = (lat * Math.PI) / 180;
  return Math.log(Math.tan(Math.PI / 4 + p / 2));
}

/** Projects lat/lon to the map plane (x east, z south, y up). */
export function project(lat: number, lon: number): [number, number] {
  const x = ((lon - CENTER_LON) * Math.PI) / 180 * MAP_SCALE;
  const z = -(merc(lat) - CENTER_MERC) * MAP_SCALE;
  return [x, z];
}

/** Texture domain of the baked land mask (lon/lat bounds). The shader maps world xz back into this. */
export const TEX_LON: [number, number] = [86, 270];
export const TEX_LAT: [number, number] = [2, 72];
export function texBounds() {
  const [x0] = project(0, TEX_LON[0]);
  const [x1] = project(0, TEX_LON[1]);
  const [, zS] = project(TEX_LAT[0], 0);
  const [, zN] = project(TEX_LAT[1], 0);
  return { x0, x1, zS, zN };
}

